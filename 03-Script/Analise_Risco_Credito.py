import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv('/content/cs-training.csv')

"""##EXPLORAÇÃO DOS DADOS"""

df.head()

df.info()

df.describe()

df.isnull().sum()

"""##LIMPEZA E TRATAMENTO DOS DADOS"""

if 'Unnamed: 0' in df.columns:

    df = df.drop(columns=['Unnamed: 0'])

df['MonthlyIncome_missing'] = df['MonthlyIncome'].isnull().astype(int)

mediana_renda = df['MonthlyIncome'].median()
df['MonthlyIncome'] = df['MonthlyIncome'].fillna(mediana_renda)

df['NumberOfDependents'] = df['NumberOfDependents'].fillna(0).astype('int64')

df.isnull().sum()

"""##ANÁLISE DO PERFIL DO INADIMPLENTE"""

print("--- Proporção Geral de Inadimplência (%) ---")
df['SeriousDlqin2yrs'].value_counts(normalize=True) * 100

print("--- Média de Idade por Status de Pagamento ---")
df.groupby('SeriousDlqin2yrs')['age'].mean()

print("--- Mediana de Renda por Status de Pagamento ---")
df.groupby('SeriousDlqin2yrs')['MonthlyIncome'].median()

print("--- 1. Histórico de Atrasos Curtos (30-59 dias) ---")
df.groupby('SeriousDlqin2yrs')['NumberOfTime30-59DaysPastDueNotWorse'].mean()

print("\n--- 2. Histórico de Atrasos Longos (90 dias ou mais) ---")
df.groupby('SeriousDlqin2yrs')['NumberOfTimes90DaysLate'].mean()

print("\n--- 3. Uso do Limite do Cartão/Cheque Especial ---")
df.groupby('SeriousDlqin2yrs')['RevolvingUtilizationOfUnsecuredLines'].median()

"""##VISUALIZAÇÃO DOS DADOS

"""

plt.figure(figsize=(6,4))
ax = sns.countplot(x='SeriousDlqin2yrs', data=df)
total = len(df)
for p in ax.patches:
    percentage = f'{100 * p.get_height() / total:.1f}%'
    x = p.get_x() + p.get_width() / 2
    y = p.get_height()
    ax.annotate(percentage, (x, y), ha='center', va='bottom')
plt.title('Distribuição de Inadimplência (%)')
plt.show()

plt.figure(figsize=(6,4))
df.groupby('SeriousDlqin2yrs')['age'].mean().plot(kind='bar')
plt.title('Média de Idade por Status de Pagamento')
plt.xlabel('Status (0 = Ok | 1 = Inadimplente)')
plt.ylabel('Idade Média')
plt.xticks(rotation=0)
plt.show()

plt.figure(figsize=(6,4))
df.groupby('SeriousDlqin2yrs')['MonthlyIncome'].median().plot(kind='bar')
plt.title('Mediana de Renda por Status')
plt.xlabel('Status')
plt.ylabel('Renda')
plt.xticks(rotation=0)
plt.show()

plt.figure(figsize=(6,4))
df.groupby('SeriousDlqin2yrs')['NumberOfTime30-59DaysPastDueNotWorse'].mean().plot(kind='bar')
plt.title('Média de Atrasos (30-59 dias)')
plt.xlabel('Status')
plt.ylabel('Quantidade média')
plt.xticks(rotation=0)
plt.show()

plt.figure(figsize=(6,4))
df.groupby('SeriousDlqin2yrs')['RevolvingUtilizationOfUnsecuredLines'].median().plot(kind='bar')
plt.title('Uso de Crédito (Mediana)')
plt.xlabel('Status')
plt.ylabel('Utilização')
plt.xticks(rotation=0)
plt.show()

